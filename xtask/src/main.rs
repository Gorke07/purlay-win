//! Repository tasks.
//!
//! ```text
//! cargo xtask contract fetch [vX.Y.Z]   download the server's contract bundle (gh release download)
//! cargo xtask contract use DIR           copy a bundle built by `bun run contract:bundle --out DIR`
//! cargo xtask contract verify            check every file against MANIFEST.json and the lock
//! cargo xtask generate [--check]         regenerate the wire types, API methods and tokens
//! ```
//!
//! Wire facts are never written by hand: the server's bundle is the single source.

mod bundle;
mod gen_api;
mod gen_tokens;
mod gen_types;
mod naming;

use anyhow::{Context, Result, bail};
use std::path::{Path, PathBuf};

fn main() -> Result<()> {
    let args: Vec<String> = std::env::args().skip(1).collect();
    let root = workspace_root();
    match args.iter().map(String::as_str).collect::<Vec<_>>().as_slice() {
        ["contract", "fetch"] => bundle::fetch(&root, None),
        ["contract", "fetch", tag] => bundle::fetch(&root, Some(tag)),
        ["contract", "use", dir] => bundle::use_dir(&root, Path::new(dir)),
        ["contract", "verify"] => bundle::verify(&root).map(|_| ()),
        ["generate"] => generate(&root, false),
        ["generate", "--check"] => generate(&root, true),
        _ => {
            eprintln!(
                "usage:\n  cargo xtask contract fetch [vX.Y.Z]\n  cargo xtask contract use DIR\n  cargo xtask contract verify\n  cargo xtask generate [--check]"
            );
            bail!("unknown command: {args:?}")
        }
    }
}

fn workspace_root() -> PathBuf {
    let manifest = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    manifest.parent().expect("xtask lives in the workspace").to_path_buf()
}

fn generate(root: &Path, check: bool) -> Result<()> {
    let bundle_dir = bundle::verify(root)?;
    let contract: serde_json::Value = read_json(&bundle_dir.join("contract.json"))?;
    let tokens: serde_json::Value = read_json(&bundle_dir.join("tokens.json"))?;
    let pairs: serde_json::Value = read_json(&bundle_dir.join("pairs.json"))?;
    let lock = bundle::Lock::read(root)?;

    let contract_out = root.join("crates/purlay-contract/src/generated");
    let core_out = root.join("crates/purlay-core/src/generated");
    let tokens_out = root.join("crates/purlay-tokens/src/generated");

    let mut files: Vec<(PathBuf, String)> = Vec::new();
    let types = gen_types::generate(&contract)?;
    files.push((contract_out.join("models.rs"), types.models));
    files.push((contract_out.join("constants.rs"), gen_types::constants(&contract, &lock)?));
    files.push((contract_out.join("endpoints.rs"), gen_api::endpoints(&contract)?));
    files.push((contract_out.join("mod.rs"), CONTRACT_MOD.to_string()));
    files.push((core_out.join("api.rs"), gen_api::client_methods(&contract)?));
    files.push((core_out.join("mod.rs"), CORE_MOD.to_string()));
    files.push((tokens_out.join("tokens.rs"), gen_tokens::generate(&tokens, &pairs)?));
    files.push((tokens_out.join("mod.rs"), TOKENS_MOD.to_string()));

    let mut stale = Vec::new();
    for (path, body) in &files {
        let body = format!("{HEADER}{body}");
        let current = std::fs::read_to_string(path).unwrap_or_default();
        if current.replace("\r\n", "\n") == body {
            continue;
        }
        if check {
            stale.push(path.display().to_string());
        } else {
            std::fs::create_dir_all(path.parent().unwrap())?;
            std::fs::write(path, body).with_context(|| format!("write {}", path.display()))?;
            println!("wrote {}", path.strip_prefix(root).unwrap_or(path).display());
        }
    }
    if !stale.is_empty() {
        bail!("generated code is stale; run `cargo xtask generate`:\n  {}", stale.join("\n  "));
    }
    println!(
        "generated from contract {} (server {}): {} schemas, {} endpoints",
        lock.contract_version,
        lock.server_version,
        types.schema_count,
        contract["endpoints"].as_array().map(|a| a.len()).unwrap_or(0)
    );
    Ok(())
}

pub fn read_json(path: &Path) -> Result<serde_json::Value> {
    let text = std::fs::read_to_string(path).with_context(|| format!("read {}", path.display()))?;
    serde_json::from_str(&text).with_context(|| format!("parse {}", path.display()))
}

const HEADER: &str = "// @generated by `cargo xtask generate` from the Purlay contract bundle.\n// Do not edit by hand: change the generator (xtask/) or pin another bundle.\n\n";

const CONTRACT_MOD: &str = "pub mod constants;\npub mod endpoints;\npub mod models;\n";
const CORE_MOD: &str = "pub mod api;\n";
const TOKENS_MOD: &str = "pub mod tokens;\n";
