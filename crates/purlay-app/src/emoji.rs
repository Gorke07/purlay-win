mod tests {
    #[test]
    fn finds_in_both_languages() {
        assert!(super::search("thumbs").contains(&"👍"));
        assert!(super::search("kalp").contains(&"❤️"));
        assert_eq!(super::search("").len(), super::EMOJI.len());
    }
}
