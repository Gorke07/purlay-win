/// Emoji matching a search, by either language's words; all of them for an empty query.
pub fn search(q: &str) -> Vec<&'static str> {
    let q = q.trim().to_lowercase();
    if q.is_empty() {
        return EMOJI.iter().map(|(e, _, _)| *e).collect();
    }
    EMOJI
        .iter()
        .filter(|(e, en, tr)| *e == q || en.split(' ').any(|w| w.starts_with(&q)) || tr.split(' ').any(|w| w.starts_with(&q)))
        .map(|(e, _, _)| *e)
        .collect()
}

